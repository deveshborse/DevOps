# Marks of 5 subjects
subject1 = 85
subject2 = 72
subject3 = 90
subject4 = 78
subject5 = 95

# Calculate total marks
total = subject1 + subject2 + subject3 + subject4 + subject5

# Calculate average
average = total / 5

# Calculate percentage (each subject is out of 100)
percentage = (total / 500) * 100

# Display results
print("Marks in Subject 1:", subject1)
print("Marks in Subject 2:", subject2)
print("Marks in Subject 3:", subject3)
print("Marks in Subject 4:", subject4)
print("Marks in Subject 5:", subject5)

print("\nTotal Marks:", total, "/ 500")
print("Average Marks:", average)
print("Percentage:", percentage, "%")